export const MARKDOWN_MEDIA_TYPE = "text/markdown; charset=utf-8";

function named(items: { name: string; desc: string }[]): string {
  return items.map((item) => `- **${item.name}.** ${item.desc}`).join("\n");
}

function chartLines(list: FidelityChart[]): string[] {
  if (list.length === 0) return [];
  const lines = list.map(
    (chart) =>
      `- **${chart.label}**, ${chart.hint} (${chart.better} is better): ${chart.bars.map((bar) => `${bar.who} ${bar.text}`).join(", ")}`,
  );
  return [...lines, ""];
}

// each card as on the page: quality bars, then time bars, then the README's full table;
// in suite order, passed in by callers (see publishedFidelity)
function benchmarks(formats: FidelityFormat[], evals: AgentEvals | null): string {
  if (formats.length === 0) return "";
  const cards = [...formats]
    .sort((a, b) => editorOrder(a.format) - editorOrder(b.format))
    .map((f) => {
      const drawn = fidelityCharts(f);
      return [
        `### ${EDITORS.find((editor) => editor.format === f.format)?.name ?? f.format.toUpperCase()} (.${f.format})`,
        "",
        ...chartLines(drawn.filter((chart) => chart.group === "quality")),
        ...chartLines(drawn.filter((chart) => chart.group === "time")),
        "All results:",
        "",
        `| | BetterOffice ([${f.commit}](${f.commitUrl})) | LibreOffice (${f.libreoffice}) |`,
        "| --- | ---: | ---: |",
        ...f.rows.map((row) => `| ${row.label} | ${row.ours} | ${row.theirs} |`),
      ].join("\n");
    });
  const shared = sharedVersion(formats);
  const version = shared
    ? `BetterOffice [${shared.commit}](${shared.commitUrl}), LibreOffice ${shared.libreoffice}\n\n`
    : "";
  return `## ${BENCHMARKS_SECTION.heading}

Generated by the [Benchmarks action](${BENCHMARKS_SECTION.workflow}); per-document results are on the [benchmarks site](${BENCHMARKS_SITE}). For how scores, timings and coverage are measured, see the [benchmark methodology](${BENCHMARKS_SECTION.methodology}).

${cards.join("\n\n")}

${version}[${BENCHMARKS_SECTION.more}](${BENCHMARKS_SITE})

${agentEdits(evals)}`;
}

function agentEdits(evals: AgentEvals | null): string {
  const cards = agentEvalCards(evals).sort((a, b) => editorOrder(a.format) - editorOrder(b.format));
  if (cards.length === 0) return "";
  const lines = cards.map((card) =>
    `- **${EDITORS.find((editor) => editor.format === card.format)?.name ?? card.format.toUpperCase()}** (.${card.format}): ${card.bars.map((bar) => `${bar.who} ${bar.text}`).join(", ")}`,
  );
  return `### ${AGENT_EVALS.heading}

${AGENT_EVALS.lead(agentEvalTasks(evals))}

${lines.join("\n")}

[${AGENT_EVALS.more}](${AGENT_EVALS.method})

`;
}

// the page's sections in the page's order; page-twin.test.js holds the two together
export function homepageMarkdown(
  fidelity: FidelityFormat[] = [],
  evals: AgentEvals | null = null,
  posts: BlogPost[] = [],
): string {
  const editors = EDITORS.map(
    (editor) =>
      `- **${editor.name}** (\`.${editor.format}\`, ${editor.status}) — ${editor.desc}${editor.demo ? ` [Demo](${DEMO}/${editor.format})` : ""}`,
  ).join("\n");

  const packages = PACKAGES.map(
    (pkg) =>
      `- [\`${pkg.name}\`](https://www.npmjs.com/package/${pkg.name}) — ${pkg.desc}`,
  ).join("\n");

  const ecosystems = ECOSYSTEMS.map(
    (eco) =>
      `- **${eco.name}** (\`${eco.install}\`) — ${eco.desc} [${eco.registry}](${eco.url}), [guide](${eco.docs})`,
  ).join("\n");

  return `# ${HERO.title}

${HERO.tagline}

- [Demos](${DEMO})
- [Documentation](${DOCS})
- [GitHub](${REPO})
${posts.length ? `- [Blog](${BLOG_MARKDOWN_URL})\n` : ""}- [Full index for agents](${SITE}/llms.txt)

${usedByLine()}

## ${SUITE.heading}

${SUITE.prose}

${editors}

## ${FOUNDATION.heading}

${FOUNDATION.prose}

${named(CAPABILITIES)}

[${FEATURES_LINK.label}](${FEATURES_LINK.href})

${benchmarks(fidelity, evals)}## ${COLLABORATION.heading}

${COLLABORATION.prose}

[Collaboration guide](${DOCS}/docs/collaboration)

${named(PEERS)}

## ${PACKAGES_SECTION.heading}

${PACKAGES_SECTION.prose}

See the [package guide](${DOCS}/docs/packages) for supported runtimes and fonts, and [release notes](${RELEASES}) for version-specific changes.

One install line per ecosystem:

${ecosystems}

${packages}

## ${CODA.heading}

[Try it out](${DEMO}), or [explore the docs](${DOCS}) for setup, APIs, and format support.
`;
}
