// Generates crates/xlsx-parse/src/table_style_presets.rs from ECMA-376 Part 1
// `presetTableStyles.xml` (in OfficeOpenXML-SpreadsheetMLStyles.zip):
// bun scripts/generate-xlsx-table-style-presets.ts <presetTableStyles.xml>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  throw new Error('usage: generate-xlsx-table-style-presets.ts <presetTableStyles.xml>');
}
const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../crates/xlsx-parse/src/table_style_presets.rs',
);

const ORDER = [
  'wholeTable',
  'firstColumnStripe',
  'secondColumnStripe',
  'firstRowStripe',
  'secondRowStripe',
  'lastColumn',
  'firstColumn',
  'headerRow',
  'totalRow',
  'firstHeaderCell',
  'lastHeaderCell',
  'firstTotalCell',
  'lastTotalCell',
];

const xml = readFileSync(source, 'utf8');
const color = (element: string | undefined) => {
  const theme = element?.match(/theme="(\d+)"/)?.[1];
  if (theme === undefined) {
    if (element) throw new Error(`unsupported color: ${element}`);
    return 'None';
  }
  const tint = Number(element?.match(/tint="([^"]+)"/)?.[1] ?? 0);
  return `Some((${theme}, ${Number.isInteger(tint) ? tint.toFixed(1) : tint}))`;
};

const styles: string[] = [];
for (const [, name, body] of xml.matchAll(/<(TableStyle\w+)>([\s\S]*?)<\/\1>/g)) {
  const dxfs = [...body.matchAll(/<dxf>([\s\S]*?)<\/dxf>/g)].map(([, dxf]) => dxf);
  const elements = [...body.matchAll(/<tableStyleElement type="(\w+)"(?: size="\d+")? dxfId="(\d+)"/g)]
    .map(([, type, id]) => {
      if (!ORDER.includes(type)) throw new Error(`unsupported element: ${type}`);
      // The preset file numbers its dxfs from 1.
      const dxf = dxfs[Number(id) - 1];
      if (dxf === undefined) throw new Error(`${name} ${type}: no dxf ${id}`);
      const font = dxf.match(/<font>([\s\S]*?)<\/font>/)?.[1] ?? '';
      const fill = dxf.match(/<fill>([\s\S]*?)<\/fill>/)?.[1] ?? '';
      if (fill && !fill.includes('patternType="solid"')) throw new Error(`${name}: unsupported fill`);
      return {
        order: ORDER.indexOf(type),
        type: type[0].toUpperCase() + type.slice(1),
        bold: /<b\s*\/>/.test(font),
        font: color(font.match(/<color[^>]*\/>/)?.[0]),
        fill: color(fill.match(/<fgColor[^>]*\/>/)?.[0]),
      };
    })
    .filter((element) => element.bold || element.font !== 'None' || element.fill !== 'None')
    .sort((a, b) => a.order - b.order)
    .map(({ type, bold, font, fill }) => `        Preset(${type}, ${bold}, ${font}, ${fill}),`);
  styles.push(`    ("${name}", &[\n${elements.join('\n')}\n    ]),`);
}
if (styles.length !== 60) throw new Error(`expected 60 table styles, found ${styles.length}`);

writeFileSync(
  out,
  `//! Excel's built-in table styles: the fill, font colour and bold of each element
//! in ECMA-376 Part 1 \`presetTableStyles.xml\`, © Ecma International.
//! Generated by \`scripts/generate-xlsx-table-style-presets.ts\`; do not edit.

use xlsx_model::TableStyleElementType::{self, *};

/// An element's type, bold, and \`(theme, tint)\` font and fill colours.
pub(crate) struct Preset(
    pub TableStyleElementType,
    pub bool,
    pub Option<(u8, f64)>,
    pub Option<(u8, f64)>,
);

#[rustfmt::skip]
pub(crate) const PRESETS: &[(&str, &[Preset])] = &[
${styles.join('\n')}
];
`,
);
