use std::collections::BTreeMap;
use std::path::Path;

use pptx_edit::DeckSession;
use yrs::updates::decoder::Decode;
use yrs::{Any, Doc, Map, Out, ReadTxn, Transact, Update};

fn fixture(name: &str) -> Vec<u8> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/old-peer")
        .join(name);
    std::fs::read(&path).unwrap_or_else(|error| {
        panic!(
            "required old-peer fixture {} could not be read: {error}; generate deck.pptx and main-update.bin with .lane/oldpeer against main's schema 2.3 sources",
            path.display()
        )
    })
}

#[test]
fn main_update_preserves_authored_strike_bytes_with_source() {
    let source = fixture("deck.pptx");
    let update = fixture("main-update.bin");
    let doc = Doc::new();
    doc.transact_mut()
        .apply_update(
            Update::decode_v1(&update).expect("main fixture must be a full Yrs v1 update"),
        )
        .expect("main fixture must hydrate a document");
    let txn = doc.transact();
    let meta = txn
        .get_map("pptx:meta")
        .expect("main fixture must have deck metadata");
    let schema_version = match meta.get(&txn, "schemaVersion") {
        Some(Out::Any(Any::Number(version))) => version,
        _ => panic!("main fixture must declare a numeric deck schema version"),
    };
    assert_eq!(
        schema_version, 2.3,
        "main-update.bin must be generated by main's pre-strike engine"
    );
    drop(txn);

    let source_parts: BTreeMap<_, _> = ooxml_opc::unzip_parts(&source)
        .expect("source fixture must be a PPTX")
        .into_iter()
        .collect();
    let source_slide = source_parts
        .get("ppt/slides/slide1.xml")
        .expect("source must have slide 1");
    let source_xml = std::str::from_utf8(source_slide).expect("slide 1 XML must be UTF-8");
    for strike in ["sngStrike", "dblStrike", "noStrike"] {
        assert!(
            source_xml.contains(&format!(r#"strike="{strike}""#)),
            "source must author {strike}"
        );
    }

    let session = DeckSession::open_from_update_with_source(&update, &source, 24103)
        .expect("this engine must open main's schema 2.3 update with its source");
    let saved = session.save().expect("migrated old-peer session must save");
    let saved_parts: BTreeMap<_, _> = ooxml_opc::unzip_parts(&saved)
        .expect("saved deck must be a PPTX")
        .into_iter()
        .collect();
    assert_eq!(
        saved_parts
            .get("ppt/slides/slide1.xml")
            .expect("saved deck must have slide 1"),
        source_slide,
        "slide 1 must retain its authored XML bytes exactly"
    );
    assert_ne!(
        saved_parts
            .get("ppt/slides/slide2.xml")
            .expect("saved deck must have slide 2"),
        source_parts
            .get("ppt/slides/slide2.xml")
            .expect("source must have slide 2"),
        "the old peer's slide 2 edit must be saved"
    );
    let reopened = DeckSession::open(&saved, 24104).expect("saved deck must reopen");
    let snapshot = reopened
        .snapshot()
        .expect("saved deck must have a snapshot");
    assert_eq!(snapshot.slides.len(), 2);
    assert_eq!(
        snapshot.slides[1].shapes[0].text_stories[0].plain_text(),
        "XPlain"
    );
}
